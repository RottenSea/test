public class If {

    public static void main(String[] args) {
        int a = 12;
        int b = 13;
        if (a < b) {
            System.out.println("a: " + a + " is less than " + "b: " + b);
        } else {
            System.out.println("a: " + a + " is not less than " + "b: " + b);
        }
    }
}
